from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]


def test_role_bootstrap_handles_empty_database_then_preserves_audit_permissions():
    image = os.getenv("XRAY_POSTGRES_TEST_IMAGE")
    if not image:
        pytest.skip("XRAY_POSTGRES_TEST_IMAGE is required for the PostgreSQL role gate")
    script = r"""
set -eu
initdb -D /tmp/xray-role-data --no-locale -U xray_owner -A trust >/dev/null
pg_ctl -D /tmp/xray-role-data -o "-c listen_addresses='' -k /tmp" -w start >/dev/null
trap 'pg_ctl -D /tmp/xray-role-data -m immediate stop >/dev/null' EXIT
export PGHOST=/tmp PGUSER=xray_owner PGDATABASE=postgres
export XRAY_ADMIN_DB_PASSWORD=fixture-admin
export XRAY_SUBSCRIPTION_DB_PASSWORD=fixture-subscription
export XRAY_WORKER_DB_PASSWORD=fixture-worker
export XRAY_OUTBOX_DB_PASSWORD=fixture-outbox
psql -X -q -v ON_ERROR_STOP=1 -f /roles.sql
psql -X -q -v ON_ERROR_STOP=1 <<'SQL'
CREATE TABLE audit_auditevent (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
CREATE TABLE cloud_accounts_cloudaccount (id bigint PRIMARY KEY);
CREATE TABLE subscriptions_subscription (id bigint PRIMARY KEY);
SQL
psql -X -q -v ON_ERROR_STOP=1 -f /roles.sql
psql -X -q -v ON_ERROR_STOP=1 -f /roles.sql
psql -X -At -v ON_ERROR_STOP=1 <<'SQL'
SELECT has_table_privilege('xray_worker', 'audit_auditevent', 'SELECT')
   AND has_table_privilege('xray_worker', 'audit_auditevent', 'INSERT')
   AND NOT has_table_privilege('xray_worker', 'audit_auditevent', 'UPDATE')
   AND NOT has_table_privilege('xray_worker', 'audit_auditevent', 'DELETE')
   AND has_sequence_privilege('xray_worker', 'audit_auditevent_id_seq', 'USAGE')
   AND has_sequence_privilege('xray_worker', 'audit_auditevent_id_seq', 'SELECT')
   AND has_table_privilege('xray_admin_api', 'audit_auditevent', 'INSERT')
   AND NOT has_table_privilege('xray_admin_api', 'audit_auditevent', 'UPDATE')
   AND NOT has_table_privilege('xray_admin_api', 'audit_auditevent', 'DELETE')
   AND has_table_privilege('xray_subscription_reader', 'subscriptions_subscription', 'SELECT')
   AND NOT has_table_privilege('xray_subscription_reader', 'cloud_accounts_cloudaccount', 'SELECT');
SQL
"""
    result = subprocess.run(
        [
            "docker",
            "run",
            "--rm",
            "--network",
            "none",
            "--read-only",
            "--user",
            "70:70",
            "--tmpfs",
            "/tmp:rw,nosuid,size=128m,uid=70,gid=70",
            "--mount",
            f"type=bind,src={ROOT / 'deploy/postgres/roles.sql'},dst=/roles.sql,readonly",
            "--entrypoint",
            "/bin/sh",
            image,
            "-ec",
            script,
        ],
        text=True,
        capture_output=True,
        timeout=90,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.strip().splitlines()[-1] == "t"
